"""Collect every result file into docs/detector-results.md (tables for the documentation and the thesis).

    python3 research/report.py --eval=/path/to/eval
"""
import argparse, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "smallmines", "results")
PAPER = [
    ("Random forest (paper)", "RGB", 0.4109, 0.9238, 0.4253, 0.5825),
    ("SAM-2* (paper)", "RGB", 0.4261, 0.7416, 0.5004, 0.5976),
    ("U-Net* ResNet-50 (paper)", "RGB", 0.7539, 0.9278, 0.8009, 0.8597),
    ("Random forest (paper)", "RGB+", 0.5027, 0.9531, 0.5155, 0.6691),
    ("U-Net (paper)", "RGB+", 0.6513, 0.9642, 0.6675, 0.7889),
    ("Prithvi-EO-2.0* 300M (paper)", "RGB+", 0.7579, 0.8558, 0.8689, 0.8623),
    ("Prithvi-EO-2.0* 600M (paper)", "RGB+", 0.7560, 0.8457, 0.8769, 0.8610),
]


def f(v):
    return f"{v:.3f}" if isinstance(v, (int, float)) else str(v)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--eval", default="/home/claude/data/eval"); a = ap.parse_args()
    L = ["# Detector 3.0 — results", "", "Generated by `research/report.py` from the result files; every number below is reproducible with the scripts in `research/`.", ""]
    L += ["## 1. SmallMinesDS benchmark (official test split, mining class, pixel-wise)", "",
          "Ofori-Ampofo et al. (2025), Table I, against GhanaWatch models trained on the same training split. * = pretrained. RGB+ = R, G, B, NIR, SWIR1, SWIR2.", "",
          "| Model | Inputs | IoU | Precision | Recall | F1 |", "|---|---|---|---|---|---|"]
    for name, inp, iou, p, r, f1 in PAPER:
        L.append(f"| {name} | {inp} | {iou:.3f} | {p:.3f} | {r:.3f} | {f1:.3f} |")
    gb = json.load(open(os.path.join(RES, "gbm_ablation.json"))) if os.path.exists(os.path.join(RES, "gbm_ablation.json")) else {}
    for name, v in gb.items():
        L.append(f"| GhanaWatch gradient boosting | {name} | {f(v['IoU'])} | {f(v['precision'])} | {f(v['recall'])} | {f(v['F1'])} |")
    ue = json.load(open(os.path.join(RES, "unet_eval.json"))) if os.path.exists(os.path.join(RES, "unet_eval.json")) else {}
    if "A_test/sentinel2_full" in ue:
        v = ue["A_test/sentinel2_full"]
        L.append(f"| **GhanaWatch U-Net* ResNet-18** | all 24 channels (10 bands, 7 indices, VV/VH, terrain) | **{f(v['IoU'])}** | {f(v['precision'])} | {f(v['recall'])} | **{f(v['F1'])}** |")
    L.append("")
    if ue:
        L += ["## 2. The U-Net on what a month can offer", "",
              "A = SmallMinesDS patches; B = GhanaWatch's own January 2022 composites at the test footprints (the production inputs). Landsat = red edge hidden and NIR from B8A; cloud = random holes with no optical data; radar only = no optical data at all; 20 m = inputs averaged to 20 m (cells outside the gold belt).", "",
              "| Test set / regime | IoU | Precision | Recall | F1 |", "|---|---|---|---|---|"]
        for k, v in ue.items():
            L.append(f"| {k} | {f(v['IoU'])} | {f(v['precision'])} | {f(v['recall'])} | {f(v['F1'])} |")
        L.append("")
    sc = os.path.join(a.eval, "score.json")
    if os.path.exists(sc):
        s = json.load(open(sc))
        L += ["## 3. Old detector against new detector on held-out ground", "",
              f"{s['patches']} test patches in blocks b2_3 and b3_3 (south-western Ghana), {s['minedPixels2022']:,} pixels mapped as mining by the experts in January 2022, of which {s['newMiningPixels2016to2022']:,} were not mining in January 2016. Both detectors run with the production code, month by month.", "",
              "| Method | IoU | Precision | Recall | F1 | Recall on new mining since 2016 |", "|---|---|---|---|---|---|"]
        for k, v in s["methods"].items():
            m = v["all mining (2022 mask)"]
            L.append(f"| {k} | {f(m['IoU'])} | {f(m['precision'])} | {f(m['recall'])} | {f(m['F1'])} | {f(v['recall on new mining since 2016'])} |")
        if s.get("onset"):
            L += ["", "Onset dates against the two expert maps:", ""]
            for k, v in s["onset"].items():
                L.append(f"- {k}: {v}")
        L.append("")
    cov = []
    for b in ("b2_3", "b3_3"):
        p = os.path.join(a.eval, b, "coverage.json")
        if os.path.exists(p):
            cov += json.load(open(p))
    if cov:
        import collections
        by = collections.defaultdict(list)
        for c in cov: by[c["month"][5:7]].append(c)
        L += ["## 4. Which sensor saw the ground, by calendar month (evaluation blocks, 2019-07 to 2022-01)", "",
              "Share of pixels whose month was observed by Sentinel-2, by Landsat only, by radar only, or not at all. The old detector used Sentinel-2 alone.", "",
              "| Month | Sentinel-2 | Landsat only | Radar only | Nothing |", "|---|---|---|---|---|"]
        for mo in sorted(by):
            v = by[mo]; avg = lambda k: sum(x[k] for x in v) / len(v)
            L.append(f"| {mo} | {avg('sentinel2'):.0%} | {avg('landsat'):.0%} | {avg('radarOnly'):.0%} | {avg('none'):.0%} |")
        L.append("")
    meta = os.path.join(RES, "unet_meta.json")
    if os.path.exists(meta):
        m = json.load(open(meta))
        L += ["## 5. Training", "", f"Encoder {m['encoder']}, {m['epochs']} epochs of {m['per_epoch']} patches; per-epoch check on 400 B-test patches:", "",
              "| Epoch | Loss | IoU | F1 | Minutes |", "|---|---|---|---|---|"]
        for e in m["log"]:
            q = e.get("B_test_quick", {})
            L.append(f"| {e['epoch']} | {e['loss']:.3f} | {f(q.get('IoU', ''))} | {f(q.get('F1', ''))} | {e['minutes']} |")
        L.append("")
    out = os.path.join(HERE, "..", "docs", "detector-results.md")
    open(out, "w").write("\n".join(L) + "\n")
    print(out)


if __name__ == "__main__":
    main()
